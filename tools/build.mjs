// Build script for Jackpot Words.
//   node tools/build.mjs
// - Validates the secret-word lists in words/*.txt
// - Builds js/data/words.js (secret words) and js/data/dict.js (allowed guesses)
// - Writes sw.js with a precache list and a content-hash version, so a new
//   deploy updates the installed iPad app automatically.
import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const LENGTHS = [5, 6, 7];
const TIERS = ['easy', 'normal', 'hard'];

const readWords = (f) =>
  readFileSync(join(ROOT, f), 'utf8').toLowerCase().split(/\s+/).filter(Boolean);

// ---- Allowed-guess dictionary -------------------------------------------
const DICT_SRC = '/usr/share/dict/words';
const dict = new Set();
if (existsSync(DICT_SRC)) {
  for (const w of readFileSync(DICT_SRC, 'utf8').split('\n')) {
    if (/^[a-z]{3,7}$/.test(w)) dict.add(w);
  }
} else {
  console.warn('No system dictionary found; only list words will be accepted.');
}
const web2 = new Set(dict);
for (const w of readWords('words/extra-valid.txt')) if (/^[a-z]{3,7}$/.test(w)) dict.add(w);

// ---- Secret words --------------------------------------------------------
const answers = {};
const seen = new Map();
let problems = 0;
for (const len of LENGTHS) {
  answers[len] = {};
  for (const tier of TIERS) {
    const file = `words/${len}-${tier}.txt`;
    const out = [];
    for (const w of readWords(file)) {
      if (!/^[a-z]+$/.test(w) || w.length !== len) {
        console.log(`  drop ${file}: "${w}" (length ${w.length})`);
        problems++;
        continue;
      }
      if (seen.has(w)) continue; // keep first (easiest) tier
      seen.set(w, file);
      out.push(w);
      dict.add(w);
    }
    answers[len][tier] = out;
  }
}

// Words that are not in Webster's list: print so a human can eyeball them.
const notInWeb2 = [...seen.keys()].filter((w) => !web2.has(w));
if (notInWeb2.length) console.log(`  ${notInWeb2.length} list words not in system dictionary (kept): ${notInWeb2.join(' ')}`);

// Deterministic shuffle so the daily puzzle order is not alphabetical-ish.
function shuffle(arr, seed) {
  let s = seed >>> 0;
  const rnd = () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296);
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

let wordsJs = '// Generated by tools/build.mjs. Edit words/*.txt instead.\nexport const ANSWERS = {\n';
for (const len of LENGTHS) {
  wordsJs += `  ${len}: {\n`;
  for (const tier of TIERS) {
    const list = shuffle(answers[len][tier], len * 97 + tier.length * 13);
    wordsJs += `    ${tier}: ${JSON.stringify(list.join(' '))},\n`;
  }
  wordsJs += '  },\n';
}
wordsJs += '};\n';
writeFileSync(join(ROOT, 'js/data/words.js'), wordsJs);

// Dictionary packed by length with no separators (every word has the same length).
const byLen = {};
for (const w of dict) (byLen[w.length] ||= []).push(w);
let dictJs = '// Generated by tools/build.mjs from the system word list (public domain) plus words/*.txt.\nexport const DICT = {\n';
for (const len of Object.keys(byLen).sort()) {
  dictJs += `  ${len}: "${byLen[len].sort().join('')}",\n`;
}
dictJs += '};\n';
writeFileSync(join(ROOT, 'js/data/dict.js'), dictJs);

// ---- Service worker -----------------------------------------------------
const PRECACHE_DIRS = ['css', 'js', 'vendor', 'fonts', 'icons'];
const files = ['index.html', 'manifest.webmanifest'];
function walk(dir) {
  for (const name of readdirSync(join(ROOT, dir))) {
    const rel = join(dir, name);
    const st = statSync(join(ROOT, rel));
    if (st.isDirectory()) walk(rel);
    else if (!/(\.txt|LICENSE|\.DS_Store)$/.test(name)) files.push(rel);
  }
}
for (const d of PRECACHE_DIRS) if (existsSync(join(ROOT, d))) walk(d);
files.sort();
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(ROOT, f)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// Generated by tools/build.mjs. Caches the whole game so it runs offline.
const VERSION = 'jackpot-${version}';
const ASSETS = ${JSON.stringify(['./', ...files], null, 2)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(ASSETS)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith(
    caches.match(req, { ignoreSearch: true }).then((hit) => {
      if (hit) return hit;
      return fetch(req).then((res) => {
        if (res.ok) {
          const copy = res.clone();
          caches.open(VERSION).then((c) => c.put(req, copy));
        }
        return res;
      }).catch(() => caches.match('./index.html'));
    })
  );
});
`;
writeFileSync(join(ROOT, 'sw.js'), sw);

// ---- Report --------------------------------------------------------------
for (const len of LENGTHS) {
  console.log(`  ${len} letters: ` + TIERS.map((t) => `${t} ${answers[len][t].length}`).join(', '));
}
console.log(`  dictionary: ${dict.size} words; sw version ${version}; ${files.length} cached files`);
if (problems) console.log(`  ${problems} list problems (see above)`);
